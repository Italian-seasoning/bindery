export type Mood = keyof typeof FACES;
export const ROWS = 7;
export const FACE_W = 13;

/** Glyph columns for text: 5 wide, 1-cell gap, uppercased, unknown characters become spaces. */
export function textGrid(text: string, glyphs: number): boolean[][] {
  const chars = [...text.toUpperCase().padEnd(glyphs, ' ').slice(0, glyphs)];
  const w = glyphs * 6 - 1;
  const grid = Array.from({ length: ROWS }, () => Array(w).fill(false));
  chars.forEach((ch, i) => {
    const rows = GLYPHS[ch] ?? GLYPHS[' '];
    rows.forEach((row, y) => { for (let x = 0; x < 5; x++) if (row[x] === '#') grid[y][i * 6 + x] = true; });
  });
  return grid;
}

export function faceGrid(mood: string): boolean[][] {
  const rows = FACES[mood] ?? FACES.idle;
  return rows.map((r) => [...r].map((c) => c === '#'));
}

/** A readout line: optional face, a 2-column gap, then text. Width is fixed by `glyphs`. */
export function lineGrid({ face, text = '', glyphs = 0 }: { face?: string | null; text?: string; glyphs?: number }): boolean[][] {
  const parts: boolean[][][] = [];
  if (face !== undefined) parts.push(faceGrid(face ?? 'sleep'));
  if (glyphs) parts.push(textGrid(text, glyphs));
  return Array.from({ length: ROWS }, (_, y) => parts.flatMap((p, i) => (i ? [false, false, ...p[y]] : p[y])));
}
